"""LLM-assisted test-case generator.

Asks Claude to propose edge-case telemetry payloads from the API's OpenAPI
schema, validates the shape of its answer, and writes them to
tests/generated/cases.json. The file is committed and reviewed by a human;
the test suite replays it without calling any model, so CI stays
deterministic and offline.

    ANTHROPIC_API_KEY=... python -m tools.gen_cases            # 20 cases
    ANTHROPIC_API_KEY=... python -m tools.gen_cases --count 40 --model claude-opus-5-5
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

OUT_PATH = Path(__file__).resolve().parent.parent / "tests" / "generated" / "cases.json"
DEFAULT_MODEL = "claude-sonnet-5-5"
ALLOWED_STATUS = {201, 422}

PROMPT = """You are a senior test engineer. Below is the JSON schema for the request body
of POST /telemetry on a FastAPI + Pydantic v2 service (lax mode; unknown fields are ignored).

{schema}

Propose {count} distinct, high-value test cases that probe boundaries, type coercion,
and malformed input. For each, predict the HTTP status: 201 if Pydantic accepts it,
422 if it rejects it. Reply with ONLY a JSON array, no prose, of objects:
{{"name": str (snake_case, unique), "payload": any JSON value,
  "expected_status": 201 | 422, "rationale": str (one sentence)}}"""


class CaseFormatError(ValueError):
    """The model's reply was not a usable list of test cases."""


def build_prompt(schema: dict[str, Any], count: int) -> str:
    return PROMPT.format(schema=json.dumps(schema, indent=2), count=count)


def parse_cases(text: str) -> list[dict[str, Any]]:
    """Extract and validate the JSON array of cases from a model reply."""
    match = re.search(r"\[.*\]", text, re.DOTALL)
    if not match:
        raise CaseFormatError("no JSON array in reply")
    try:
        cases = json.loads(match.group(0))
    except json.JSONDecodeError as exc:
        raise CaseFormatError(f"invalid JSON: {exc}") from exc

    seen: set[str] = set()
    for i, case in enumerate(cases):
        if not isinstance(case, dict) or not {"name", "payload", "expected_status"} <= set(case):
            raise CaseFormatError(f"case {i} is missing required keys")
        if case["expected_status"] not in ALLOWED_STATUS:
            raise CaseFormatError(f"case {case['name']!r} has status {case['expected_status']}")
        if case["name"] in seen:
            raise CaseFormatError(f"duplicate case name {case['name']!r}")
        seen.add(case["name"])
        case.setdefault("rationale", "")
    return cases


def generate(client: Any, model: str, schema: dict[str, Any], count: int) -> list[dict]:
    """Call the Messages API once and return validated cases."""
    reply = client.messages.create(
        model=model,
        max_tokens=4096,
        messages=[{"role": "user", "content": build_prompt(schema, count)}],
    )
    text = "".join(block.text for block in reply.content if getattr(block, "type", "") == "text")
    return parse_cases(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--count", type=int, default=20)
    parser.add_argument("--model", default=os.getenv("CASEGEN_MODEL", DEFAULT_MODEL))
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    args = parser.parse_args(argv)

    if not os.getenv("ANTHROPIC_API_KEY"):
        print("ANTHROPIC_API_KEY is not set; nothing generated.", file=sys.stderr)
        return 2

    import anthropic  # optional dependency, only needed to regenerate

    from app.app import Telemetry

    cases = generate(anthropic.Anthropic(), args.model, Telemetry.model_json_schema(), args.count)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    document = {
        "source": f"Generated by tools/gen_cases.py with {args.model}",
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "review": "Unreviewed. Check every expected_status before committing.",
        "cases": cases,
    }
    args.out.write_text(json.dumps(document, indent=2) + "\n")
    print(f"Wrote {len(cases)} cases to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
